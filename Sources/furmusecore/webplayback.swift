// which engine plays the spotify source. both stay in the app; only one runs at a time (two connect devices named
// "furmuse" would fight over the same account).
enum SpotifyBackend: String, CaseIterable {
    case webplayback, librespot
    var label: String {
        switch self {
        case .webplayback: return "web playback sdk"
        case .librespot: return "librespot"
        }
    }
}

struct WebTrackInfo: Equatable {
    var uri: String, id: String, type: String, name: String, artist: String, album: String, cover: String
    var artistlist: [String]? = nil
    var durationms: Int
    // ads, episodes and local files have no 22 character track id
    var istrack: Bool { type == "track" && id.count == 22 }
    var track: Track {
        Track(id: id, title: name, artist: artist, album: album, artwork: cover.isEmpty ? nil : cover, duration: Double(durationms) / 1000, artists: artistlist)
    }
}

struct WebPlayerState: Equatable {
    var paused: Bool
    var loading: Bool
    var positionms: Int
    var durationms: Int
    var track: WebTrackInfo?
    var previous: [String]
    var nextcount: Int
    var shuffle: Bool
    var repeatmode: Int
    var context: String
    var received: Date      // local clock when this state arrived: position is extrapolated from here, never from spotify's timestamp

    func liveposition(at now: Date = Date()) -> Int {
        if paused || loading { return positionms }
        let p = positionms + max(0, Int(now.timeIntervalSince(received) * 1000))
        return durationms > 0 ? min(p, durationms) : p
    }

    static func parse(_ o: [String: Any]) -> WebPlayerState {
        func int(_ v: Any?) -> Int { (v as? NSNumber)?.intValue ?? 0 }
        var t: WebTrackInfo?
        if let d = o["track"] as? [String: Any] {
            t = WebTrackInfo(uri: d["uri"] as? String ?? "", id: d["id"] as? String ?? "", type: d["type"] as? String ?? "",
                             name: d["name"] as? String ?? "", artist: d["artists"] as? String ?? "", album: d["album"] as? String ?? "",
                             cover: d["cover"] as? String ?? "", artistlist: d["artistlist"] as? [String], durationms: int(d["duration_ms"]))
        }
        return WebPlayerState(paused: (o["paused"] as? Bool) ?? true, loading: (o["loading"] as? Bool) ?? false,
                              positionms: int(o["position"]), durationms: int(o["duration"]), track: t,
                              previous: (o["prev"] as? [String]) ?? [], nextcount: int(o["nextn"]),
                              shuffle: (o["shuffle"] as? Bool) ?? false, repeatmode: int(o["repeat"]),
                              context: o["context"] as? String ?? "", received: Date())
    }
}

// owns the single Web Playback SDK player for the app.
//
// the SDK is javascript, so it runs in a WKWebView (see WebPlayerPage). the web view is a 1x1 nearly transparent view in
// the key window: a web view that is not in a window gets throttled by WebKit. it is created when spotify is enabled, signs
// in with the access token furmuse already has (SpotifyAuth, the user's own client id), and registers a real connect
// device. nothing has to be cast from another spotify app first.
//
// threading: every method here runs on the main thread (web view delegates and Task { @MainActor } blocks).
final class WebPlaybackSession: NSObject, ObservableObject, WKScriptMessageHandler, WKNavigationDelegate {
    static let shared = WebPlaybackSession()
    static let devicename = "Furmuse"

    enum Phase: String { case stopped, loading, connecting, ready, reconnecting, failed, blocked }

    @Published private(set) var phase: Phase = .stopped
    @Published private(set) var deviceid: String?        // generated by spotify's SDK at every connect, never stored as truth
    @Published private(set) var lasterror: String?
    @Published private(set) var state: WebPlayerState?
    @Published private(set) var activationneeded = false
    @Published private(set) var volumecontrol: Bool?     // nil = not tested yet; false = this device ignores programmatic volume

    var statehandler: ((WebPlayerState?) -> Void)?       // the active playback source
    var adoptsink: ((WebPlayerState?) -> Void)?          // the engine: playback that another spotify client started on this device
    var errorhandler: ((String) -> Void)?                // playback_error text for the active source
    var volumeprovider: () -> Double = { 1 }
    private(set) var lastcommandedplay = Date.distantPast

    private var auth: SpotifyAuth?
    private var api: SpotifyAPI?
    private var devices: DeviceManager?
    private var web: WKWebView?
    private var enabled = false
    private var observing = false
    private var monitor: NWPathMonitor?
    private var watchdog: Timer?
    private var waiters: [(id: UUID, cont: CheckedContinuation<String, Error>)] = []
    private var failures = 0
    private var nextattempt = Date.distantPast
    private var phasesince = Date()
    private var tokenforce = false
    private var authfailures = 0

    var statustext: String {
        switch phase {
        case .stopped: return enabled ? "starting" : "off"
        case .loading: return "loading the sdk"
        case .connecting: return "connecting to spotify"
        case .ready: return "ready"
        case .reconnecting: return "reconnecting"
        case .failed: return "failed"
        case .blocked: return "blocked"
        }
    }

    // ---- setup ------------------------------------------------------------------------------------------------------
    @MainActor
    func configure(auth: SpotifyAuth, api: SpotifyAPI, devices: DeviceManager) {
        self.auth = auth
        self.api = api
        self.devices = devices
    }

    // enabled: start (or keep alive) the player. disabled: shut it down and take the device off spotify.
    @MainActor
    func supervise(enabled: Bool) {
        let was = self.enabled
        self.enabled = enabled
        guard enabled else { if was || web != nil { stop() }; return }
        installobservers()
        kick(force: false)
    }

    @MainActor
    func stop() {
        enabled = false
        teardownweb()
        deviceid = nil
        state = nil
        lasterror = nil
        activationneeded = false
        setphase(.stopped)
        resolvewaiters(.failure(SourceError.unavailable("spotify web playback is off")))
        Log.i(.webplayback, "web player stopped")
    }

    // manual retry from settings
    @MainActor
    func restart() {
        failures = 0
        nextattempt = .distantPast
        authfailures = 0
        teardownweb()
        setphase(.stopped)
        kick(force: true)
    }

    // the first thing that stops web playback, in words the user can act on. nil = nothing known to be wrong.
    func blocker() -> String? {
        guard let a = auth else { return "web playback isn't set up yet" }
        if a.clientid.isEmpty { return "no spotify client id. enter yours in setup (settings → spotify)" }
        if !a.connected { return "spotify isn't connected. settings → spotify → connect" }
        if a.scopesok == false {
            return "this spotify login lacks permissions web playback needs (\(a.missingscopes.joined(separator: ", "))). settings → spotify → disconnect, then connect again"
        }
        return nil
    }

    private func setphase(_ p: Phase) {
        guard p != phase else { return }
        phase = p
        phasesince = Date()
    }

    // starts the web view if it isn't running and nothing is wrong. safe to call often (watchdog, network, foreground).
    @MainActor
    func kick(force: Bool = false) {
        guard enabled else { return }
        if let why = blocker() {
            if phase != .blocked || lasterror != why { lasterror = why; setphase(.blocked); resolvewaiters(.failure(SourceError.unavailable(why))) }
            // signed out or lost a scope while running: take the device off spotify instead of leaving it half alive
            if web != nil { teardownweb(); state = nil; activationneeded = false; Log.i(.webplayback, "web player taken down: \(why)") }
            return
        }
        switch phase {
        case .ready: return
        case .loading, .connecting:
            // never got there: treat as a failed attempt and rebuild
            if Date().timeIntervalSince(phasesince) > 25 { Log.w(.webplayback, "no ready event after 25 s, rebuilding"); failures += 1; nextattempt = Date().addingTimeInterval(backoff()) }
            else { return }
        default: break
        }
        guard force || Date() >= nextattempt else { return }
        teardownweb()
        lasterror = nil
        setphase(.loading)
        if !buildweb() {
            // no window yet (very early launch): try again shortly
            setphase(.stopped)
            DispatchQueue.main.asyncAfter(deadline: .now() + 1) { [weak self] in Task { @MainActor in self?.kick() } }
            return
        }
        Log.i(.webplayback, "starting web player")
    }

    private func backoff() -> TimeInterval { min(120, 4 * pow(2.0, Double(min(failures, 5)))) }

    private func installobservers() {
        guard !observing else { return }
        observing = true
        let m = NWPathMonitor()
        m.pathUpdateHandler = { [weak self] path in
            guard path.status == .satisfied else { return }
            DispatchQueue.main.async { Task { @MainActor in self?.nextattempt = .distantPast; self?.kick() } }
        }
        m.start(queue: DispatchQueue(label: "furmuse.webplayback.path"))
        monitor = m
        let nc = NotificationCenter.default
        nc.addObserver(forName: UIApplication.willEnterForegroundNotification, object: nil, queue: .main) { [weak self] _ in
            Task { @MainActor in self?.nextattempt = .distantPast; self?.layoutweb(); self?.kick() }
        }
        nc.addObserver(forName: UIWindow.didBecomeKeyNotification, object: nil, queue: .main) { [weak self] _ in
            Task { @MainActor in self?.kick() }
        }
        watchdog = Timer.scheduledTimer(withTimeInterval: 20, repeats: true) { [weak self] _ in Task { @MainActor in self?.kick() } }
    }

    // ---- web view ---------------------------------------------------------------------------------------------------
    private func keywindow() -> UIWindow? {
        UIApplication.shared.connectedScenes.compactMap { $0 as? UIWindowScene }.flatMap { $0.windows }.first { $0.isKeyWindow }
    }

    private func buildweb() -> Bool {
        guard web == nil else { return true }
        guard let window = keywindow() else { return false }
        let cfg = WKWebViewConfiguration()
        cfg.allowsInlineMediaPlayback = true
        cfg.mediaTypesRequiringUserActionForPlayback = []
        cfg.allowsAirPlayForMediaPlayback = true
        cfg.userContentController.add(self, name: "wolf")
        let w = WKWebView(frame: CGRect(x: 0, y: 0, width: 1, height: 1), configuration: cfg)
        w.navigationDelegate = self
        w.isOpaque = false
        w.backgroundColor = .clear
        w.scrollView.isScrollEnabled = false
        w.alpha = 0.01
        w.isUserInteractionEnabled = false
        #if DEBUG
        if #available(iOS 16.4, *) { w.isInspectable = true }
        #endif
        window.insertSubview(w, at: 0)
        web = w
        w.loadHTMLString(WebPlayerPage.html, baseURL: URL(string: WebPlayerPage.origin))
        return true
    }

    private func teardownweb() {
        guard let w = web else { return }
        web = nil
        w.navigationDelegate = nil
        // let the page disconnect the player first so the device leaves spotify's list cleanly, then drop the view
        var done = false
        let cleanup = {
            guard !done else { return }
            done = true
            w.configuration.userContentController.removeScriptMessageHandler(forName: "wolf")
            w.stopLoading()
            w.removeFromSuperview()
        }
        w.evaluateJavaScript("window.wolf && window.wolf.dispose()") { _, _ in cleanup() }
        DispatchQueue.main.asyncAfter(deadline: .now() + 2) { cleanup() }
        deviceid = nil
    }

    // the page shows its own "tap to enable spotify audio" button; the view grows from 1x1 to a bar while it is needed.
    // the tap has to land inside the page itself: that is the user gesture the SDK's activateElement() requires.
    private func setactivation(_ on: Bool) {
        guard on != activationneeded else { return }
        activationneeded = on
        layoutweb()
        Log.i(.webplayback, on ? "audio activation needed: showing the tap bar" : "audio activated")
    }

    private func layoutweb() {
        guard let w = web, let window = (w.superview as? UIWindow) ?? keywindow() else { return }
        if activationneeded {
            w.frame = CGRect(x: 16, y: window.safeAreaInsets.top + 72, width: max(120, window.bounds.width - 32), height: 60)
            w.alpha = 1
            w.isUserInteractionEnabled = true
            w.layer.cornerRadius = 12
            w.clipsToBounds = true
            window.bringSubviewToFront(w)
        } else {
            w.frame = CGRect(x: 0, y: 0, width: 1, height: 1)
            w.alpha = 0.01
            w.isUserInteractionEnabled = false
            window.sendSubviewToBack(w)
        }
    }

    // json-encodes one string as a javascript literal (tokens go through here, so no string building by hand)
    private func js(_ s: String) -> String {
        guard let d = try? JSONSerialization.data(withJSONObject: s, options: [.fragmentsAllowed]),
              let t = String(data: d, encoding: .utf8) else { return "\"\"" }
        return t
    }

    // never logs the script: it can contain an access token
    private func eval(_ script: String) {
        guard let w = web else { return }
        w.evaluateJavaScript(script) { _, err in
            if let err = err { Log.w(.webplayback, "page script error: \(err.localizedDescription)") }
        }
    }

    // ---- commands to the SDK player ------------------------------------------------------------------------------
    func send(_ name: String, _ arg: Double = 0) {
        if !Thread.isMainThread { DispatchQueue.main.async { self.send(name, arg) }; return }
        guard web != nil else { return }
        eval("window.wolf.cmd(\(js(name)), \(arg))")
    }

    func setvolume(_ v: Double) { send("volume", min(1, max(0, v))) }

    // ---- navigation delegate --------------------------------------------------------------------------------------
    func webView(_ webView: WKWebView, decidePolicyFor navigationAction: WKNavigationAction, decisionHandler: @escaping (WKNavigationActionPolicy) -> Void) {
        // the SDK builds its own iframes; the page itself may only ever be furmuse's own page
        if navigationAction.targetFrame?.isMainFrame == false { decisionHandler(.allow); return }
        let u = navigationAction.request.url?.absoluteString ?? ""
        decisionHandler(u.hasPrefix(WebPlayerPage.origin) || u == "about:blank" ? .allow : .cancel)
    }

    func webView(_ webView: WKWebView, didFinish navigation: WKNavigation!) {
        guard webView === web else { return }
        let v = min(1, max(0, volumeprovider()))
        eval("window.wolf.init(\(js(WebPlaybackSession.devicename)), \(v))")
    }

    func webView(_ webView: WKWebView, didFail navigation: WKNavigation!, withError error: Error) { navfailed(webView, error) }
    func webView(_ webView: WKWebView, didFailProvisionalNavigation navigation: WKNavigation!, withError error: Error) { navfailed(webView, error) }

    private func navfailed(_ webView: WKWebView, _ error: Error) {
        guard webView === web else { return }
        fail("the web player page didn't load: \(error.localizedDescription)", .failed)
    }

    func webViewWebContentProcessDidTerminate(_ webView: WKWebView) {
        guard webView === web else { return }
        Log.w(.webplayback, "web content process terminated, rebuilding")
        deviceid = nil
        teardownweb()
        setphase(.reconnecting)
        nextattempt = .distantPast
        Task { @MainActor in self.kick() }
    }

    // ---- messages from the page -----------------------------------------------------------------------------------
    func userContentController(_ userContentController: WKUserContentController, didReceive message: WKScriptMessage) {
        guard message.frameInfo.isMainFrame, let body = message.body as? [String: Any], let type = body["type"] as? String else { return }
        switch type {
        case "sdk_loaded":
            setphase(.connecting)
            Log.i(.webplayback, "sdk loaded, player created")
        case "ready":
            guard let id = body["device_id"] as? String, !id.isEmpty else { return }
            deviceid = id
            lasterror = nil
            failures = 0
            authfailures = 0
            setphase(.ready)
            Log.i(.webplayback, "connect device ready as \"\(WebPlaybackSession.devicename)\"")
            send("volume", min(1, max(0, volumeprovider())))
            send("activate")     // harmless where the web view allows autoplay; the tap bar covers the rest
            devices?.adoptown(id)
            Task { @MainActor in await self.devices?.refresh() }
            resolvewaiters(.success(id))
        case "not_ready":
            // spotify says the device went offline (network change, session dropped). reconnect the same player first.
            Log.w(.webplayback, "device not ready, reconnecting")
            deviceid = nil
            setphase(.reconnecting)
            nextattempt = Date().addingTimeInterval(10)     // if the SDK doesn't come back by itself, the watchdog rebuilds
            send("connect")
        case "connectresult":
            if (body["ok"] as? Bool) == false {
                let why = (body["err"] as? String) ?? "spotify refused the connection"
                Log.w(.webplayback, "connect() returned false: \(why)")
                if phase == .connecting || phase == .loading { fail("couldn't connect the web player to spotify: \(why)", .failed) }
            }
        case "state":
            let s = (body["state"] as? [String: Any]).map(WebPlayerState.parse)
            state = s
            if let s = s, !s.paused, activationneeded { setactivation(false) }
            statehandler?(s)
            adoptsink?(s)
        case "token_request":
            guard let id = body["id"] as? String else { return }
            Task { @MainActor in await self.serve(tokenid: id) }
        case "autoplay_failed":
            Log.w(.webplayback, "autoplay was blocked")
            setactivation(true)
        case "activated":
            setactivation(false)
        case "volume":
            let req = (body["requested"] as? NSNumber)?.doubleValue ?? 0
            let act = (body["actual"] as? NSNumber)?.doubleValue ?? req
            let honoured = abs(req - act) < 0.05
            if volumecontrol != honoured {
                volumecontrol = honoured
                if !honoured { Log.w(.webplayback, "this web view ignores programmatic volume (asked \(req), got \(act)); use the hardware volume buttons") }
            }
        case "cmdresult":
            if (body["ok"] as? Bool) == false {
                Log.w(.webplayback, "command \(body["name"] as? String ?? "?") failed: \(body["err"] as? String ?? "")")
            }
        case "error":
            handleerror(kind: body["kind"] as? String ?? "", message: body["message"] as? String ?? "")
        default: break
        }
    }

    private func handleerror(kind: String, message: String) {
        Log.e(.webplayback, "\(kind): \(message)")
        switch kind {
        case "initialization_error":
            fail("this web view couldn't start spotify's web playback sdk (\(message)). it needs DRM (encrypted media) support. you can switch to librespot in settings → audio source.", .failed)
        case "authentication_error":
            // the token was refused: fetch a fresh one once, then give up with a clear message
            authfailures += 1
            if authfailures <= 1 {
                tokenforce = true
                send("connect")
            } else {
                fail("spotify rejected the login for web playback (\(message)). disconnect and connect spotify again in settings.", .failed)
            }
        case "account_error":
            fail("spotify says this account can't use web playback. it needs spotify premium (mobile-only premium plans are excluded). (\(message))", .blocked)
        case "playback_error":
            errorhandler?(message.isEmpty ? "spotify couldn't play this track" : message)
        case "sdk_load_failed":
            fail("couldn't load spotify's web playback sdk. check your connection.", .failed)
        case "token_unavailable":
            break      // serve(tokenid:) already set the state
        case "activation_error":
            ToastCenter.shared.show("couldn't enable spotify audio: \(message)", route: .source)
        default: break
        }
    }

    private func fail(_ text: String, _ p: Phase) {
        lasterror = text
        failures += 1
        nextattempt = Date().addingTimeInterval(backoff())
        setphase(p)
        resolvewaiters(.failure(SourceError.unavailable(text)))
        Log.e(.webplayback, "web player \(p.rawValue): \(text)")
    }

    // the SDK asks for an access token at connect time and whenever it needs a new one
    @MainActor
    private func serve(tokenid id: String) async {
        guard let a = auth else { eval("window.wolf.tokenfail(\(js(id)), \(js("not set up")))"); return }
        do {
            let force = tokenforce
            tokenforce = false
            let tok = try await a.token(force: force)
            if a.scopesok == false {
                let why = blocker() ?? "missing scopes"
                lasterror = why
                setphase(.blocked)
                resolvewaiters(.failure(SourceError.unavailable(why)))
                eval("window.wolf.tokenfail(\(js(id)), \(js("missing scopes")))")
                return
            }
            eval("window.wolf.token(\(js(id)), \(js(tok)))")
        } catch {
            Log.w(.webplayback, "no access token for the sdk: \((error as? SpotifyError).map { "\($0)" } ?? error.localizedDescription)")
            eval("window.wolf.tokenfail(\(js(id)), \(js("no access token")))")
        }
    }

    // ---- waiting for the device ------------------------------------------------------------------------------------
    private func resolvewaiters(_ r: Result<String, Error>) {
        guard !waiters.isEmpty else { return }
        let list = waiters
        waiters.removeAll()
        for w in list {
            switch r {
            case .success(let id): w.cont.resume(returning: id)
            case .failure(let e): w.cont.resume(throwing: e)
            }
        }
    }

    private func timeout(_ id: UUID) {
        guard let i = waiters.firstIndex(where: { $0.id == id }) else { return }
        let w = waiters.remove(at: i)
        w.cont.resume(throwing: SourceError.unavailable("spotify's web player didn't become ready in time (status: \(statustext)\(lasterror.map { ", " + $0 } ?? ""))"))
    }

    // returns the device id once the SDK has reported `ready`; throws an explanation otherwise
    @MainActor
    func ensureready(wait: TimeInterval = 20) async throws -> String {
        if let why = blocker() { throw SourceError.unavailable(why) }
        if !enabled { throw SourceError.unavailable("spotify web playback is off (settings → audio source)") }
        if phase == .ready, let id = deviceid { return id }
        if phase == .failed { restart() } else { kick(force: phase == .stopped) }
        if let why = blocker() { throw SourceError.unavailable(why) }
        return try await withCheckedThrowingContinuation { (c: CheckedContinuation<String, Error>) in
            let wid = UUID()
            waiters.append((id: wid, cont: c))
            DispatchQueue.main.asyncAfter(deadline: .now() + wait) { [weak self] in self?.timeout(wid) }
        }
    }

    // ---- playback --------------------------------------------------------------------------------------------------
    // the SDK has no "play this uri" call: playback is started through the Web API on this device's generated id, then the
    // SDK reports what it is doing. the device can take a moment to show up in spotify's list after `ready`, so a 404 is
    // answered with a transfer to it and a retry.
    @MainActor
    func start(uri: String, positionms: Int) async throws {
        _ = try await ensureready()
        guard let api = api else { throw SourceError.unavailable("spotify api isn't available") }
        lastcommandedplay = Date()
        var lasterr: Error?
        for _ in 0..<3 {
            guard let id = deviceid else { throw SourceError.unavailable("spotify's web player went offline, try again") }
            do {
                _ = try await api.request("PUT", "/me/player/play", query: ["device_id": id], body: ["uris": [uri], "position_ms": max(0, positionms)])
                lasterr = nil
                break
            } catch {
                lasterr = error
                guard case .nodevice? = error as? SpotifyError else { break }
                Log.w(.webplayback, "device not in spotify's list yet, transferring playback to it")
                _ = try? await api.request("PUT", "/me/player", body: ["device_ids": [id], "play": false])
                // The transfer request itself registers/activates the device. A short scheduler
                // yield is normally sufficient; the old fixed 700 ms delay penalised every cold play.
                try? await Task.sleep(nanoseconds: 180_000_000)
            }
        }
        if let e = lasterr { throw WebPlaybackSession.map(e) }
        try await confirm(uri: uri)
    }

    // moves the user's current spotify playback to this device (connect "transfer playback")
    @MainActor
    func transferhere(play: Bool) async throws {
        let id = try await ensureready()
        guard let api = api else { throw SourceError.unavailable("spotify api isn't available") }
        do { _ = try await api.request("PUT", "/me/player", body: ["device_ids": [id], "play": play]) }
        catch { throw WebPlaybackSession.map(error) }
        lastcommandedplay = Date()
    }

    @MainActor
    func resumeFromUserGesture() {
        send("resume")
        // WKWebView can accept the command while its audio context is still suspended. Keep the
        // activation affordance/state armed until player_state_changed confirms audible playback.
        setactivation(true)
    }

    // waits until the SDK says this track is playing. on iOS the web view can load the track but keep it paused until
    // it has had a user gesture: then the tap bar is shown.
    @MainActor
    private func confirm(uri: String) async throws {
        let began = Date()
        var nudged = false
        while Date().timeIntervalSince(began) < 6 {
            if let s = state, s.track?.uri == uri, !s.paused { return }
            if !nudged, Date().timeIntervalSince(began) > 1, let s = state, s.track?.uri == uri, s.paused {
                nudged = true
                send("resume")
                setactivation(true)
            }
            try await Task.sleep(nanoseconds: 100_000_000)
        }
        setactivation(true)
        throw SourceError.failed("spotify loaded the track but the web player didn't start audio. tap \"tap to enable spotify audio\" at the top of the screen, then play again")
    }

    static func map(_ e: Error) -> SourceError {
        switch e as? SpotifyError {
        case .premiumrequired?: return .unavailable("spotify premium is required to play through furmuse")
        case .nodevice?: return .unavailable("spotify can't find furmuse's web player in your device list. try again in a moment")
        case .notconnected?: return .unavailable("spotify isn't connected. settings → spotify → connect")
        case .quota?: return .unavailable("spotify quota exceeded for this app")
        case .rate(let s)?: return .unavailable("spotify rate limit, retry in \(s)s")
        case .network?: return .unavailable("couldn't reach spotify")
        case .http(let c, _)?: return .failed("spotify returned an error (\(c))")
        default: return .failed(e.localizedDescription)
        }
    }
}
